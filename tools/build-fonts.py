#!/usr/bin/env python3
"""Build the bundled watermark fonts from a Maple Mono release directory.

The watermark is drawn on a canvas, so every face it may use has to be loaded
by the page before the first render — shipping the release as-is (16 faces,
~20 MB each) would be 326 MB of TTF in the image for a feature that only ever
sets a camera model, four exposure numbers and a timestamp.

So each face is subset to the character repertoire a watermark can actually
contain and re-packed as WOFF2. That is ~40 KB per face instead of 20 MB, which
is small enough to ship all sixteen and let the user pick any of them.

    python tools/build-fonts.py "T:/path/to/maple-mono" --write
    python tools/build-fonts.py "T:/path/to/maple-mono" --check

`--check` compares the generated CSS against what is on disk and exits non-zero
if a rebuild is needed, so CI can guard the assets.

Characters outside the subset (CJK typed into a text field, say) fall back
through the renderer's font stack to the platform font — canvas does that
per-glyph, exactly like CSS.

Needs `pip install fonttools brotli` (brotli is what makes WOFF2 possible).
The generated .woff2 files and web/css/fonts.css are committed, so a normal
build never runs this.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "web" / "assets" / "fonts"
CSS_OUT = ROOT / "web" / "css" / "fonts.css"

# What a watermark can contain: printable ASCII, Latin-1 and Latin Extended-A
# (names like "Müller"), general punctuation and dashes, currency (¥ €), the
# letterlike/maths symbols exposure lines use (× ÷ ≈), CJK punctuation, and
# full-width forms. Deliberately no Hanzi: 3.7k of them would be ~2.5 MB per
# face and no watermark field produces them.
UNICODES = (
    "U+0020-007E,U+00A0-00FF,U+0100-017F,U+2000-206F,U+20A0-20BF,"
    "U+2100-214F,U+2190-21FF,U+2200-22FF,U+3000-303F,U+FF00-FFEF"
)
LAYOUT_FEATURES = "kern,liga,calt"

# (file stem suffix, CSS weight, CSS style, Chinese label, English label)
FACES = [
    ("thin", 100, "normal", "极细", "Thin"),
    ("thinitalic", 100, "italic", "极细 斜体", "Thin Italic"),
    ("extralight", 200, "normal", "超细", "ExtraLight"),
    ("extralightitalic", 200, "italic", "超细 斜体", "ExtraLight Italic"),
    ("light", 300, "normal", "细体", "Light"),
    ("lightitalic", 300, "italic", "细体 斜体", "Light Italic"),
    ("regular", 400, "normal", "常规", "Regular"),
    ("italic", 400, "italic", "常规 斜体", "Italic"),
    ("medium", 500, "normal", "中等", "Medium"),
    ("mediumitalic", 500, "italic", "中等 斜体", "Medium Italic"),
    ("semibold", 600, "normal", "半粗", "SemiBold"),
    ("semibolditalic", 600, "italic", "半粗 斜体", "SemiBold Italic"),
    ("bold", 700, "normal", "粗体", "Bold"),
    ("bolditalic", 700, "italic", "粗体 斜体", "Bold Italic"),
    ("extrabold", 800, "normal", "特粗", "ExtraBold"),
    ("extrabolditalic", 800, "italic", "特粗 斜体", "ExtraBold Italic"),
]

FAMILY = "Maple Mono NF CN"
STEM = "maple-mono-nf-cn"


def source_for(src: Path, suffix: str) -> Path:
    """`regular` -> MapleMono-NF-CN-Regular.ttf; `thinitalic` -> ...-ThinItalic.ttf."""
    camel = "".join(p.capitalize() for p in re.findall(r"[a-z]+|[A-Z][a-z]*", suffix))
    for candidate in (f"MapleMono-NF-CN-{camel}.ttf", f"MapleMono-NF-CN-{camel}.otf"):
        p = src / candidate
        if p.exists():
            return p
    raise FileNotFoundError(f"{src}/MapleMono-NF-CN-{camel}.ttf")


def css_text(entries: list[dict]) -> str:
    head = (
        "/* Generated by tools/build-fonts.py — do not edit by hand.\n"
        " *\n"
        " * Maple Mono is subset to the character repertoire a watermark can\n"
        " * contain (printable ASCII, Latin-1/Extended-A, punctuation, symbols);\n"
        " * see the tool for the exact ranges. Faces are only fetched when the\n"
        " * renderer actually asks for that weight, so listing sixteen costs\n"
        " * nothing at runtime.\n"
        " *\n"
        " * Maple Mono © the Maple Mono authors, SIL Open Font License 1.1 —\n"
        " * see assets/fonts/LICENSE.txt. */\n"
    )
    blocks = []
    for e in entries:
        blocks.append(
            "@font-face {\n"
            f'  font-family: "{FAMILY}";\n'
            f"  font-weight: {e['weight']};\n"
            f"  font-style: {e['style']};\n"
            "  font-display: block;\n"
            f'  src: url("../assets/fonts/{e["file"]}") format("woff2");\n'
            "}\n"
        )
    return head + "\n".join(blocks)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("src", help="directory holding MapleMono-NF-CN-*.ttf")
    ap.add_argument("--write", action="store_true", help="build files")
    ap.add_argument("--check", action="store_true", help="fail if a rebuild is needed")
    ap.add_argument("--fonts", action="store_true", help="print the FONTS table for server/config.py")
    args = ap.parse_args()

    src = Path(args.src)
    entries = []
    for suffix, weight, style, cn, en in FACES:
        entries.append({
            "key": f"{STEM}-{suffix}",
            "label": f"{cn} · {en}",
            "weight": weight,
            "style": style,
            "family": FAMILY,
            "file": f"{STEM}-{suffix}.woff2",
            "source": source_for(src, suffix),
        })

    want_css = css_text(entries)
    have_css = CSS_OUT.read_text(encoding="utf-8") if CSS_OUT.exists() else ""
    stale = [e["file"] for e in entries if not (OUT_DIR / e["file"]).exists()]

    if args.check:
        problems = []
        if want_css != have_css:
            problems.append("web/css/fonts.css is out of date")
        if stale:
            problems.append("missing: " + ", ".join(stale))
        if problems:
            print("font assets need a rebuild:", *problems, sep="\n  ")
            return 1
        print(f"fonts ok ({len(entries)} faces)")
        return 0

    if not args.write:
        for e in entries:
            size = (OUT_DIR / e["file"]).stat().st_size if (OUT_DIR / e["file"]).exists() else 0
            print(f'{e["file"]:42} {size / 1024:7.1f} KB  <- {e["source"].name}')
        print("\n(dry run — pass --write to build)")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    total = 0
    for e in entries:
        dest = OUT_DIR / e["file"]
        subprocess.run([
            sys.executable, "-m", "fontTools.subset", str(e["source"]),
            f"--unicodes={UNICODES}",
            f"--layout-features={LAYOUT_FEATURES}",
            "--flavor=woff2",
            "--no-hinting",
            "--desubroutinize",
            f"--output-file={dest}",
        ], check=True)
        total += dest.stat().st_size
        print(f'{e["file"]:42} {dest.stat().st_size / 1024:7.1f} KB')

    license_src = src / "LICENSE.txt"
    if license_src.exists():
        shutil.copyfile(license_src, OUT_DIR / "LICENSE.txt")

    CSS_OUT.write_text(css_text(entries), encoding="utf-8", newline="\n")
    print(f"\n{len(entries)} faces, {total / 1024 / 1024:.2f} MB total -> {OUT_DIR}")
    print(f"wrote {CSS_OUT}")

    if args.fonts:
        print("\n# paste into FONTS (server/config.py)")
        for e in entries:
            print(
                '    {"key": "%s", "label": "%s", "family": "%s", "weight": %d, '
                '"style": "%s", "file": "%s"},'
                % (e["key"], e["label"], e["family"], e["weight"], e["style"], e["file"])
            )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
